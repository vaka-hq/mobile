export type Glyph = keyof typeof glyphs

const numberedSkips = new Set([5, 10, 15, 30, 45, 60])

/**
 * The skip icon for an interval: Material's circular arrow with the seconds in its middle, or the
 * plain arrow for an interval without a numbered icon.
 */
export function skipGlyph(direction: 'back' | 'forward', seconds: number): Glyph {
  if (!numberedSkips.has(seconds)) {
    return direction === 'back' ? 'skipBack' : 'skipForward'
  }

  // SAFETY: the numbered icons above exist for exactly the intervals in `numberedSkips`.
  return `${direction === 'back' ? 'skipBack' : 'skipForward'}${seconds}` as Glyph
}
